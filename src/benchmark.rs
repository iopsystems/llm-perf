    #[test]
    fn outstanding_cap_uses_generous_default_or_explicit() {
        // Explicit value above concurrency is honored.
        assert_eq!(effective_outstanding_cap(Some(500), 50), 500);
        // Default: max(concurrency * 100, 100_000).
        assert_eq!(effective_outstanding_cap(None, 50), 100_000);
        assert_eq!(effective_outstanding_cap(None, 2000), 200_000);
        // Never below concurrency — a cap under the in-flight capacity is degenerate
        // (it can't fill the pipe) and would starve `total_requests` termination.
        assert_eq!(effective_outstanding_cap(Some(10), 50), 50);
        assert_eq!(effective_outstanding_cap(Some(0), 50), 50);
    }

    #[test]
    fn throughput_window_excludes_the_discarded_tail() {
        // Throughput divides completed work by a window, so both must describe the
        // same interval. A 30s bound whose 4th request is still in flight has only
        // ~24.6s of counted work; dividing by 30 charges the run for time whose
        // output was thrown away, which is what made throughput quantise onto
        // `n * max_tokens / window` instead of converging on a rate.
        let last: LastCompletionUs = Arc::new(AtomicU64::new(0));
        last.store(24_600_000, Ordering::Relaxed);
        assert_eq!(
            throughput_window(&last, Duration::from_secs(30)),
            Duration::from_micros(24_600_000)
        );

        // Nothing completed: fall back to the wall clock rather than dividing by
        // zero and reporting an infinite rate.
        let none: LastCompletionUs = Arc::new(AtomicU64::new(0));
        assert_eq!(
            throughput_window(&none, Duration::from_secs(30)),
            Duration::from_secs(30)
        );

        // With concurrency the window is the LATEST completion, not the last one
        // recorded -- `mark_completion` uses fetch_max for exactly this.
        let racy: LastCompletionUs = Arc::new(AtomicU64::new(0));
        racy.fetch_max(9_000_000, Ordering::Relaxed);
        racy.fetch_max(3_000_000, Ordering::Relaxed);
        assert_eq!(
            throughput_window(&racy, Duration::from_secs(30)),
            Duration::from_micros(9_000_000)
        );
    }

    #[test]
    fn teardown_grace_covers_what_the_work_can_take() {
        // Regression: a flat 60s grace bounded the WHOLE closed-loop worker, so a
        // run needing longer was truncated and published as complete -- 12
        // requests at ~8.2s each reported `Sent: 7` and a round `60.0s`.

        // The ceiling must account for retries: the client deadlines each attempt
        // at `timeout` and retries `max_retries` times. Using `timeout` alone
        // understates it by (max_retries + 1) and reintroduces the bug.
        assert_eq!(request_ceiling(300, 3), Duration::from_secs(1200));
        assert_eq!(request_ceiling(300, 0), Duration::from_secs(300));

        // Closed-loop pool: one worker may run every request, so the net must
        // cover all of them, not one.
        let whole_run = teardown_grace(12, 300, 3);
        assert_eq!(whole_run, Duration::from_secs(1200 * 12 + 60));
        assert!(
            whole_run > Duration::from_secs(98),
            "must comfortably exceed the ~98s such a run actually needs"
        );

        // Teardown-only sites (one in-flight request) still get a real ceiling
        // rather than a constant that could cut a slow generation short.
        assert_eq!(teardown_grace(1, 300, 3), Duration::from_secs(1200 + 60));
        assert!(teardown_grace(1, 300, 0) > Duration::from_secs(60));

        // Zero/absurd worker counts must not collapse or overflow the net.
        assert_eq!(teardown_grace(0, 300, 3), teardown_grace(1, 300, 3));
        assert!(teardown_grace(usize::MAX, u64::MAX, u32::MAX) > Duration::from_secs(60));
    }

